import { defineConfig, lazyPlugins } from "vite-plus";
import { devtools } from "@tanstack/devtools-vite";

import { tanstackStart } from "@tanstack/react-start/plugin/vite";

import viteReact from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { nitro } from "nitro/vite";

/**
 * Sent with every response. No full script CSP: the inline theme script and the
 * framework's hydration scripts would need nonces. These directives restrict
 * nothing the app uses, and close framing, plugin content and base-URL
 * hijacking.
 */
const SECURITY_HEADERS = {
  "content-security-policy": "frame-ancestors 'none'; object-src 'none'; base-uri 'self'",
  "x-frame-options": "DENY",
  "x-content-type-options": "nosniff",
  "referrer-policy": "strict-origin-when-cross-origin",
  "cross-origin-opener-policy": "same-origin",
  "permissions-policy": "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
  // Ignored by browsers over plain http, so harmless in development.
  "strict-transport-security": "max-age=31536000",
};

/** Operator pages and every server-function response carry per-user data. */
const NO_STORE = { "cache-control": "no-store" };

const config = defineConfig({
  fmt: {
    ignorePatterns: [
      // Vendored skills are kept byte-identical to their upstream source.
      ".opencode/skills/**",
      // Generated by the router; formatting it causes a perpetual diff.
      "src/routeTree.gen.ts",
    ],
  },
  lint: {
    ignorePatterns: [".opencode/skills/**", "src/routeTree.gen.ts"],
    jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
    rules: { "vite-plus/prefer-vite-plus-imports": "error" },
    options: { typeAware: true, typeCheck: true },
  },
  resolve: { tsconfigPaths: true },
  plugins: lazyPlugins(() => [
    devtools(),
    nitro({
      rollupConfig: { external: [/^@sentry\//] },
      plugins: ["./src/server/plugins/warm-up.ts", "./src/server/plugins/notifications.ts"],
      routeRules: {
        "/**": { headers: SECURITY_HEADERS },
        "/admin": { headers: NO_STORE },
        "/admin/**": { headers: NO_STORE },
        "/_serverFn/**": { headers: NO_STORE },
        "/api/**": { headers: NO_STORE },
        // A service worker is re-checked on every navigation anyway; this stops
        // a CDN in front of the app holding an old one.
        "/sw.js": { headers: { "cache-control": "no-cache" } },
      },
    }),
    tailwindcss(),
    tanstackStart(),
    viteReact(),
  ]),
});

export default config;
